/// Flag emoji for an ISO 4217 currency code (best-effort).
///
/// Multi-country currencies (e.g. EUR) use a representative symbol.
/// Unknown codes return an empty string.
String currencyFlag(String code) {
  final c = code.toUpperCase();
  return _flags[c] ?? '';
}

String currencyLabel(String code) {
  final flag = currencyFlag(code);
  return flag.isEmpty ? code.toUpperCase() : '$flag ${code.toUpperCase()}';
}

